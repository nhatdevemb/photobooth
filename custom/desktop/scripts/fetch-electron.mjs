import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(desktop, 'node_modules/electron');
const { version } = JSON.parse(await readFile(path.join(base, 'package.json'), 'utf8'));
const name = `electron-v${version}-win32-x64.zip`;
const checksums = JSON.parse(await readFile(path.join(base, 'checksums.json'), 'utf8'));
const response = await fetch(`https://github.com/electron/electron/releases/download/v${version}/${name}`, { signal: AbortSignal.timeout(180000) });
if (!response.ok) throw new Error(`Electron download ${response.status}`);
const bytes = Buffer.from(await response.arrayBuffer());
if (createHash('sha256').update(bytes).digest('hex') !== checksums[name]) throw new Error('Electron checksum mismatch');
const zip = path.join(desktop, '.cache', name);
await writeFile(zip, bytes);
await mkdir(path.join(base, 'dist'), { recursive: true });
const extraction = spawnSync('tar.exe', ['-xf', zip, '-C', path.join(base, 'dist')], { windowsHide: true, stdio: 'inherit' });
if (extraction.error || extraction.status !== 0) throw extraction.error || new Error('Electron extraction failed');
await writeFile(path.join(base, 'path.txt'), 'electron.exe');
console.log(`Electron ${version} verified.`);
